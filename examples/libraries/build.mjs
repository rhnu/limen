import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

// Node.js runs this development tool only; Limen loads the resulting plain ESM.
const root = fileURLToPath(new URL("../../", import.meta.url));
const license = await readFile(
  new URL("../../node_modules/valibot/LICENSE.md", import.meta.url),
  "utf8",
);

await build({
  absWorkingDir: root,
  entryPoints: ["examples/libraries/src/gateway.js"],
  outfile: "examples/libraries/gateway.js",
  bundle: true,
  external: ["limen:*"],
  format: "esm",
  platform: "neutral",
  target: "es2023",
  legalComments: "inline",
  banner: {
    js: `// Generated by pnpm build:examples; edit src/gateway.js instead.\n/*\nValibot license:\n${license.trim()}\n*/`,
  },
  logLevel: "info",
});
